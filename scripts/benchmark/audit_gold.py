"""Write a NEW artifact that records the gold for every question. Never edits a frozen one.

    python scripts/benchmark/audit_gold.py

## Why this exists

`docs/performance/m0115-experiments.json` carries the project's headline
**194/202**, and it records `expect_key` for **0 of its 202 rows**. The
generator has a gold key for **175** of them. So the artifact does not record
what it graded against, and 194 cannot be checked from the file.

That is not a small gap. It means the headline is only reproducible by someone
who can re-run the generator, and it hides a question that cannot be graded at
all.

## The question that cannot be graded

Both question sets contain a **relationship-cycle** question that is answerable
and has **no gold key**:

| set | qid | text | `expect_state` | gold key |
|---|---|---|---|---|
| dev (202) | `rel-cycle` | Which two services depend on each other? | `CURRENT` | **none** |
In the dev artifact `rel-cycle` has no `keys_returned` field at all, `failure:""`
and `fallback_ok: true` -- **it is counted in the 194**. In the held-out artifact
`ho-rel-cycle` has `keys_returned: []` and is counted in the 131.
In the dev artifact `rel-cycle` has no `keys_returned` field at all, `failure:
""`, and `fallback_ok: true` — **it is counted in the 194**. In the held-out
artifact `ho-rel-cycle` has `keys_returned: []` and is counted in the 131.

So this is the same one-question discrepancy that made the lab's held-out
artifact read 140 answerable against the set's real 141: `expect_state !=
"ABSENT"` counts 141 (and 176 on dev), while `expect_key IS NOT NULL` counts 140
(and 175).

**This artifact does not change 194.** It records what 194 was measured against,
and marks the one question that was scored without gold. Whether a question with
no gold should score as a success is an owner decision, not a fix applied here.

## What it writes

`docs/performance/m0115-gold-audit.json` — a **new** file. The frozen
`m0115-experiments.json` is read and never written.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT / "scripts" / "benchmark") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts" / "benchmark"))
if str(ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts"))

FROZEN = ROOT / "docs" / "performance" / "m0115-experiments.json"
OUT = ROOT / "docs" / "performance" / "m0115-gold-audit.json"


def main() -> int:
    from m0115_dataset import build_questions, dataset_hash

    frozen = json.loads(FROZEN.read_text())
    questions = build_questions()
    by_qid = {q.qid: q for q in questions}

    rows = []
    ungradable = []
    for result in frozen["results"]:
        q = by_qid.get(result["qid"])
        if q is None:
            raise SystemExit(f"{result['qid']} is in the artifact but not in the generator")
        answerable = q.expect_state != "ABSENT"
        has_gold = q.key is not None
        row = {
            "qid": q.qid,
            "category": q.category,
            "text": q.text,
            "expect_state": q.expect_state,
            "expect_key": q.key,
            "expect_values": list(q.expect_values),
            "answerable": answerable,
            "has_gold": has_gold,
            "gradeable": answerable and has_gold,
            "recorded_ok": {
                "A_semantic": result["semantic_ok"],
                "B_lexical": result["lexical_ok"],
                "C_fallback": result["fallback_ok"],
            },
        }
        rows.append(row)
        if answerable and not has_gold:
            ungradable.append(q.qid)

    scored = {
        s: sum(1 for r in rows if r["recorded_ok"][s])
        for s in ("A_semantic", "B_lexical", "C_fallback")
    }
    gradeable = [r for r in rows if r["gradeable"]]

    body = {
        "note": (
            "Generated by scripts/benchmark/audit_gold.py. NEW file: the frozen "
            "m0115-experiments.json is read and never written. This records the "
            "gold for every question so the headline figure can be audited from "
            "a file rather than by re-running the generator."
        ),
        "source_artifact": "docs/performance/m0115-experiments.json",
        "source_dataset_hash": dataset_hash(),
        "total": len(rows),
        "answerable": sum(1 for r in rows if r["answerable"]),
        "absent": sum(1 for r in rows if not r["answerable"]),
        "with_gold_key": sum(1 for r in rows if r["has_gold"]),
        "gradeable": len(gradeable),
        "ungradable_but_scored": ungradable,
        "scored_as_recorded": scored,
        "caveat": (
            "ungradable_but_scored lists answerable questions with no gold key. "
            'They carry failure:"" and *_ok:true in the frozen artifact and are '
            "included in scored_as_recorded. Excluding them would change the "
            f"denominator from {len(rows)} to {len(gradeable)}. This artifact "
            "records that; it does not apply it."
        ),
        "rows": rows,
    }
    blob = json.dumps(body, indent=2, sort_keys=True) + "\n"
    OUT.write_text(blob)
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  questions        : {body['total']}")
    print(f"  answerable       : {body['answerable']}")
    print(f"  with a gold key  : {body['with_gold_key']}")
    print(f"  gradeable        : {body['gradeable']}")
    print(f"  scored as recorded: {json.dumps(scored)}")
    print(f"  answerable with NO gold, yet scored: {ungradable}")
    print(f"  sha256           : {hashlib.sha256(blob.encode()).hexdigest()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
