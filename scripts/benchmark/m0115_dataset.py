def dataset_hash() -> str:
    """Stable identity for the rendered corpus plus the question set."""
    docs = build_corpus()
    questions = build_questions()
    blob = json.dumps(
        {
            "documents": [{"path": d.path, "content": d.content} for d in docs],
            "questions": [
                {
                    "qid": q.qid,
                    "category": q.category,
                    "text": q.text,
                    "key": q.key,
                    "expect_state": q.expect_state,
                    "expect_values": list(q.expect_values),
                }
                for q in questions
            ],
        },
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    )
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def summary() -> dict:
    docs = build_corpus()
    questions = build_questions()
    categories: dict[str, int] = {}
    for q in questions:
        categories[q.category] = categories.get(q.category, 0) + 1
    return {
        "documents": len({d.path for d in docs}),
        "versions": len(docs),
        "questions": len(questions),
        "categories": categories,
        "dataset_hash": dataset_hash(),
    }


if __name__ == "__main__":
    print(json.dumps(summary(), indent=2, sort_keys=True))
