"""M011.5 research dataset: an evolving platform, with authored ground truth.

Everything here is authored, not generated by a model. The platform spec is the
source of truth; documents are rendered from it, and every question states what
the archive should answer and why. That keeps ground truth independent of the
retriever, so a failure is a failure of the system rather than of the label.

Shape, chosen to stress the parts that matter:

* 12 services across 4 teams, with an ownership and dependency graph
* 6 cross-cutting technologies (database, cache, queue, auth, search, storage)
* decisions that supersede earlier decisions on the same authored key
* an unreconciled ADR that conflicts with the architecture it contradicts
* incidents that introduce constraints
* a dependency cycle between two services
* deliberately irrelevant material sharing vocabulary with the real answers
* an adversarial document whose text asserts authority and instructs deletion
* a late correction that backdates a fact

Corpus and question set are deterministic. `dataset_hash` covers the rendered
documents and the questions, so a result can be tied to the exact data.
"""

