@dataclass
class Document:
    path: str
    content: str
    #: A later entry with the same path supersedes the earlier one.
    superseded_by: str | None = None


def _front_matter(
    title: str, doc_type: str, claims: list[str] | None = None, tags: list[str] | None = None
) -> str:
    lines = ["---", f'title: "{title}"', f'document_type: "{doc_type}"']
    if tags:
        lines.append("tags: [" + ", ".join(f'"{t}"' for t in tags) + "]")
    if claims:
        lines.append("claims:")
        lines.extend(claims)
    lines.append("---")
    return "\n".join(lines) + "\n"


def _claim(key: str, value: str, sentence: str, **extra) -> str:
    out = [
        f"  - key: {key}",
        f"    value: {json.dumps(value)}",
        f"    claim: {json.dumps(sentence)}",
        f"    evidence: {json.dumps(sentence)}",
    ]
    for k, v in extra.items():
        out.append(f"    {k}: {json.dumps(v)}")
    return "\n".join(out)


